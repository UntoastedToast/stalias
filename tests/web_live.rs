//! End-to-end tests of the HTTP layer against a real Stalwart. See `tests/stalwart_live.rs`
//! for the environment variables; run with `cargo test -- --ignored --test-threads=1`.

use axum::Router;
use axum::http::{StatusCode, header};
use serde_json::json;
use stalias::state::AppState;
use stalias::store::Store;
use stalias::web;

mod common;
use common::{api, form, get, send};

struct Env {
    url: String,
    key: String,
    account: String,
    domain: String,
}

fn env() -> Env {
    let var = |k: &str| std::env::var(k).unwrap_or_else(|_| panic!("{k} is not set"));
    Env {
        url: var("STALIAS_TEST_URL"),
        key: var("STALIAS_TEST_KEY"),
        account: var("STALIAS_TEST_ACCOUNT"),
        domain: var("STALIAS_TEST_DOMAIN"),
    }
}

async fn configured_app(e: &Env) -> (Router, Store) {
    let store = Store::in_memory().unwrap();
    store
        .set_stalwart(e.url.clone(), e.key.clone())
        .await
        .unwrap();
    store
        .set_domains(std::slice::from_ref(&e.domain))
        .await
        .unwrap();
    let state = AppState::new(store.clone(), Some("test-code".into()), false)
        .await
        .unwrap();
    (web::router(state), store)
}

#[tokio::test]
#[ignore]
async fn addy_api_lifecycle() {
    let e = env();
    let (app, store) = configured_app(&e).await;
    let token = store
        .create_token("test".into(), e.account.clone(), "alice".into())
        .await
        .unwrap();
    let t = Some(token.as_str());

    let created = send(
        &app,
        api(
            "POST",
            "/api/v1/aliases",
            t,
            Some(json!({
                "domain": e.domain, "description": "Website: example.com. Generated by Bitwarden."
            })),
        ),
    )
    .await;
    assert_eq!(created.status, StatusCode::CREATED, "{}", created.body);
    let email = created.json()["data"]["email"].as_str().unwrap().to_owned();
    assert!(email.ends_with(&format!("@{}", e.domain)));
    let path = format!("/api/v1/aliases/{email}");

    let listed = send(&app, api("GET", "/api/v1/aliases", t, None)).await;
    assert!(
        listed.json()["data"]
            .as_array()
            .unwrap()
            .iter()
            .any(|a| a["email"] == email.as_str())
    );

    let patched = send(
        &app,
        api("PATCH", &path, t, Some(json!({ "description": "renamed" }))),
    )
    .await;
    assert_eq!(patched.json()["data"]["description"], "renamed");

    let off = send(
        &app,
        api(
            "DELETE",
            &format!("/api/v1/active-aliases/{email}"),
            t,
            None,
        ),
    )
    .await;
    assert_eq!(off.status, StatusCode::NO_CONTENT);
    assert_eq!(
        send(&app, api("GET", &path, t, None)).await.json()["data"]["active"],
        false
    );

    let on = send(
        &app,
        api(
            "POST",
            "/api/v1/active-aliases",
            t,
            Some(json!({ "id": email })),
        ),
    )
    .await;
    assert_eq!(on.json()["data"]["active"], true);

    assert_eq!(
        send(&app, api("DELETE", &path, t, None)).await.status,
        StatusCode::NO_CONTENT
    );
    assert_eq!(
        send(&app, api("DELETE", &path, t, None)).await.status,
        StatusCode::NOT_FOUND
    );
}

#[tokio::test]
#[ignore]
async fn addy_api_rejects_bad_requests() {
    let e = env();
    let (app, store) = configured_app(&e).await;
    let token = store
        .create_token("test".into(), e.account.clone(), "alice".into())
        .await
        .unwrap();

    let no_auth = send(&app, api("POST", "/api/v1/aliases", None, Some(json!({})))).await;
    assert_eq!(no_auth.status, StatusCode::UNAUTHORIZED);
    let bad_token = send(
        &app,
        api("GET", "/api/v1/aliases", Some("stalias_nope"), None),
    )
    .await;
    assert_eq!(bad_token.status, StatusCode::UNAUTHORIZED);

    let wrong_domain = send(
        &app,
        api(
            "POST",
            "/api/v1/aliases",
            Some(&token),
            Some(json!({ "domain": "evil.example" })),
        ),
    )
    .await;
    assert_eq!(wrong_domain.status, StatusCode::UNPROCESSABLE_ENTITY);
    assert!(wrong_domain.json()["errors"]["domain"].is_array());
}

#[tokio::test]
#[ignore]
async fn setup_wizard_and_dashboard() {
    let e = env();
    let state = AppState::new(Store::in_memory().unwrap(), Some("test-code".into()), false)
        .await
        .unwrap();
    let app = web::router(state);

    assert_eq!(send(&app, get("/", None)).await.location(), "/setup");

    let wrong = send(
        &app,
        form(
            "/setup",
            None,
            &[
                ("code", "nope"),
                ("password", "longpassword"),
                ("confirm", "longpassword"),
            ],
        ),
    )
    .await;
    assert_eq!(wrong.status, StatusCode::UNAUTHORIZED);
    let short = send(
        &app,
        form(
            "/setup",
            None,
            &[
                ("code", "test-code"),
                ("password", "short"),
                ("confirm", "short"),
            ],
        ),
    )
    .await;
    assert_eq!(short.status, StatusCode::UNPROCESSABLE_ENTITY);

    let done = send(
        &app,
        form(
            "/setup",
            None,
            &[
                ("code", "test-code"),
                ("password", "longpassword"),
                ("confirm", "longpassword"),
            ],
        ),
    )
    .await;
    assert_eq!(done.status, StatusCode::SEE_OTHER);
    let cookie = done
        .headers
        .get(header::SET_COOKIE)
        .unwrap()
        .to_str()
        .unwrap()
        .split(';')
        .next()
        .unwrap()
        .to_owned();
    let c = Some(cookie.as_str());

    // A second signup must not replace the admin.
    let again = send(
        &app,
        form(
            "/setup",
            None,
            &[
                ("code", "test-code"),
                ("password", "intruder123"),
                ("confirm", "intruder123"),
            ],
        ),
    )
    .await;
    assert_eq!(again.location(), "/");
    assert_eq!(send(&app, get("/tokens", None)).await.location(), "/login");

    assert_eq!(send(&app, get("/", c)).await.location(), "/settings");
    let bad = send(
        &app,
        form("/settings", c, &[("url", &e.url), ("key", "API_invalid")]),
    )
    .await;
    assert!(
        bad.body.contains("rejected the credentials"),
        "{}",
        bad.body
    );
    let saved = send(
        &app,
        form("/settings", c, &[("url", &e.url), ("key", &e.key)]),
    )
    .await;
    assert_eq!(saved.status, StatusCode::SEE_OTHER);

    assert_eq!(
        send(&app, get("/", c)).await.location(),
        "/settings/domains"
    );
    assert_eq!(
        send(
            &app,
            form("/settings/domains", c, &[("domain", "nope.invalid")])
        )
        .await
        .status,
        StatusCode::OK
    );
    assert_eq!(
        send(&app, form("/settings/domains", c, &[("domain", &e.domain)]))
            .await
            .status,
        StatusCode::SEE_OTHER
    );

    assert_eq!(send(&app, get("/", c)).await.location(), "/tokens");
    let token_page = send(
        &app,
        form(
            "/tokens",
            c,
            &[("account_id", &e.account), ("label", "Bitwarden")],
        ),
    )
    .await;
    assert!(token_page.body.contains("stalias_"), "{}", token_page.body);

    let dashboard = send(&app, get("/", c)).await;
    assert_eq!(dashboard.status, StatusCode::OK);
    assert!(dashboard.body.contains("New alias"));

    let created = send(
        &app,
        form(
            "/aliases",
            c,
            &[
                ("account", &e.account),
                ("domain", &e.domain),
                ("local_part", "web-test"),
                ("description", ""),
            ],
        ),
    )
    .await;
    assert_eq!(created.status, StatusCode::SEE_OTHER);
    let address = format!("web-test@{}", e.domain);
    assert!(
        send(&app, get(created.location(), c))
            .await
            .body
            .contains(&address)
    );
    let toggled = send(
        &app,
        form(
            "/aliases/toggle",
            c,
            &[
                ("account", &e.account),
                ("address", &address),
                ("enabled", "false"),
            ],
        ),
    )
    .await;
    assert_eq!(toggled.status, StatusCode::SEE_OTHER);
    assert!(
        send(&app, get(&format!("/?account={}", e.account), c))
            .await
            .body
            .contains("Disabled")
    );
    send(
        &app,
        form(
            "/aliases/delete",
            c,
            &[("account", &e.account), ("address", &address)],
        ),
    )
    .await;
    assert!(
        !send(&app, get(&format!("/?account={}", e.account), c))
            .await
            .body
            .contains(&address)
    );
}
